def search_fn(head,key):
    temp=head
    while temp!=None:
        if key>temp.val:
            temp=temp.right
        elif key<temp.val:
            temp=temp.left
        else:
            break
    if temp==None:
        return "ERROR: NOT FOUND"
    else:
        return temp.lst






















































































